export function t(lang, key, vars = {}) {
  const table = STRINGS[lang] || STRINGS.tc;
  let text = table[key] ?? STRINGS.tc[key] ?? key;
  for (const [name, value] of Object.entries(vars)) {
    text = text.replaceAll(`{${name}}`, String(value));
  }
  return text;
}

export function errorText(lang, code) {
  return (ERRORS[lang] || ERRORS.tc)[code] || code;
}

export function districtLabel(lang, name) {
  const row = DISTRICTS.find((item) => item[0] === name);
  if (!row) return name;
  return lang === "en" ? row[1] : row[0];
}

export function regionLabel(lang, name) {
  const row = DISTRICTS.find((item) => item[2] === name);
  if (!row) return name;
  return lang === "en" ? row[3] : row[2];
}

export function formatHkd(value) {
  const rounded = Math.round(value);
  const sign = rounded < 0 ? "-" : "";
  return `${sign}$${Math.abs(rounded).toLocaleString("en-US")}`;
}
