export function t(lang, key, vars = {}) {
  const table = COPY[lang] || COPY.tc;
  let text = table[key] ?? COPY.tc[key] ?? key;
  return Object.entries(vars).reduce((line, [name, value]) => line.replaceAll(`{${name}}`, String(value)), text);
}

